const catalogs: Record<Language, Record<MessageKey, string>> = { fr, en };
let current: Language = 'fr';

export function setLanguage(language: Language): void {
  current = language === 'en' ? 'en' : 'fr';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = current;
  }
}

export function getLanguage(): Language {
  return current;
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  const template = catalogs[current][key] ?? fr[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    params[name] === undefined ? `{${name}}` : String(params[name])
  );
}

export function hasMessage(key: string): key is MessageKey {
  return key in fr;
}

export function formatNumber(value: number): string {
  return new Intl.NumberFormat(current === 'fr' ? 'fr-FR' : 'en-US').format(Math.round(value));
}

export function formatDate(value: Date | number | string, utc = false): string {
  const date = typeof value === 'string' ? new Date(`${value}T00:00:00Z`) : new Date(value);
  return new Intl.DateTimeFormat(current === 'fr' ? 'fr-FR' : 'en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: utc ? 'UTC' : undefined
  }).format(date);
}

